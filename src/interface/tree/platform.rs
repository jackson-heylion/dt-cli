use super::target;
use clap::{Arg, Command};

pub(super) fn environment_arg() -> Arg {
    Arg::new("environment")
        .long("environment")
        .default_value("prod")
        .value_name("prod|stg")
}

pub(super) fn platform() -> Command {
    let profile = || Arg::new("profile").long("profile");
    Command::new("dt-cli")
        .disable_help_flag(true)
        .disable_version_flag(true)
        .subcommand(super::management::command())
        .subcommand(super::context::command())
        .subcommands(super::discovery::commands())
        .subcommand(super::diagnostic::command())
        .subcommand(
            Command::new("login")
                .arg(profile().required(true))
                .args(origin_args())
                .arg(environment_arg())
                .arg(Arg::new("system").long("system").default_value("platform"))
                .arg(
                    Arg::new("no-browser")
                        .long("no-browser")
                        .action(clap::ArgAction::SetTrue),
                ),
        )
        .subcommand(Command::new("profiles"))
        .subcommand(Command::new("check").arg(profile()))
        .subcommand(
            Command::new("sessions")
                .arg(profile())
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("revoke")
                .arg(profile())
                .arg(Arg::new("session").long("session").required(true)),
        )
        .subcommand(
            Command::new("catalog")
                .arg(profile())
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(target(Command::new("views").arg(profile())))
        .subcommand(
            target(Command::new("call").arg(profile()))
                .arg(
                    Arg::new("path")
                        .long("path")
                        .required_unless_present("input-file"),
                )
                .arg(Arg::new("query").long("query").default_value(""))
                .arg(
                    Arg::new("input-file")
                        .long("input-file")
                        .conflicts_with_all(["path", "query"]),
                )
                .arg(
                    Arg::new("body-file")
                        .long("body-file")
                        .requires("input-file"),
                )
                .arg(Arg::new("view").long("view").requires("object"))
                .arg(Arg::new("object").long("object").requires("view")),
        )
        .subcommand(
            Command::new("writes")
                .subcommand(
                    Command::new("list").arg(Arg::new("page").long("page").default_value("1")),
                )
                .subcommand(
                    target(Command::new("prepare").arg(profile()))
                        .arg(Arg::new("input-file").long("input-file").required(true))
                        .arg(Arg::new("body-file").long("body-file"))
                        .arg(Arg::new("instruction").long("instruction").required(true)),
                )
                .subcommand(
                    Command::new("inspect").arg(
                        Arg::new("id")
                            .long("id")
                            .allow_hyphen_values(true)
                            .required(true),
                    ),
                )
                .subcommand(
                    Command::new("confirm")
                        .arg(profile())
                        .arg(
                            Arg::new("id")
                                .long("id")
                                .allow_hyphen_values(true)
                                .required(true),
                        )
                        .arg(Arg::new("fingerprint").long("fingerprint").required(true)),
                )
                .subcommand(
                    Command::new("dispatch").arg(profile()).arg(
                        Arg::new("id")
                            .long("id")
                            .allow_hyphen_values(true)
                            .required(true),
                    ),
                )
                .subcommand(
                    Command::new("status").arg(profile()).arg(
                        Arg::new("id")
                            .long("id")
                            .allow_hyphen_values(true)
                            .required(true),
                    ),
                ),
        )
        .subcommand(
            Command::new("jobs")
                .subcommand(
                    Command::new("list").arg(Arg::new("page").long("page").default_value("1")),
                )
                .subcommand(
                    target(Command::new("start").arg(profile()))
                        .arg(Arg::new("input-file").long("input-file").required(true))
                        .arg(Arg::new("body-file").long("body-file")),
                )
                .subcommand(
                    Command::new("resume").arg(profile()).arg(
                        Arg::new("id")
                            .long("id")
                            .allow_hyphen_values(true)
                            .required(true),
                    ),
                )
                .subcommand(
                    Command::new("status").arg(
                        Arg::new("id")
                            .long("id")
                            .allow_hyphen_values(true)
                            .required(true),
                    ),
                )
                .subcommand(
                    Command::new("results")
                        .arg(
                            Arg::new("id")
                                .long("id")
                                .allow_hyphen_values(true)
                                .required(true),
                        )
                        .arg(Arg::new("page").long("page").default_value("0")),
                ),
        )
        .subcommand(Command::new("logout").arg(profile()))
}

fn origin_args() -> Vec<Arg> {
    #[cfg(feature = "local-dev")]
    {
        vec![Arg::new("origin").long("origin").hide(true)]
    }
    #[cfg(not(feature = "local-dev"))]
    {
        vec![]
    }
}
