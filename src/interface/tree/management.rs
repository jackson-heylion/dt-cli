use clap::{Arg, Command};
pub(super) fn command() -> Command {
    let profile_arg = || Arg::new("profile").long("profile");
    Command::new("manage")
        .disable_help_flag(true)
        .subcommand(
            Command::new("login")
                .arg(profile_arg().required(true))
                .args(origin_args())
                .arg(super::platform::environment_arg())
                .arg(
                    Arg::new("no-browser")
                        .long("no-browser")
                        .action(clap::ArgAction::SetTrue),
                ),
        )
        .subcommand(Command::new("check").arg(profile_arg()))
        .subcommand(Command::new("logout").arg(profile_arg()))
        .subcommand(Command::new("capabilities").arg(profile_arg()))
        .subcommand(
            Command::new("systems")
                .arg(profile_arg())
                .arg(Arg::new("id").long("id").allow_hyphen_values(true))
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("drafts")
                .arg(profile_arg())
                .arg(
                    Arg::new("system")
                        .long("system")
                        .required_unless_present("id"),
                )
                .arg(Arg::new("id").long("id").allow_hyphen_values(true))
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("versions")
                .arg(profile_arg())
                .arg(
                    Arg::new("id")
                        .long("id")
                        .allow_hyphen_values(true)
                        .required(true),
                )
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("grants")
                .arg(profile_arg())
                .arg(
                    Arg::new("id")
                        .long("id")
                        .allow_hyphen_values(true)
                        .required(true),
                )
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("audit")
                .arg(profile_arg())
                .arg(
                    Arg::new("id")
                        .long("id")
                        .allow_hyphen_values(true)
                        .required(true),
                )
                .arg(Arg::new("page").long("page").default_value("1")),
        )
        .subcommand(
            Command::new("plan")
                .arg(profile_arg())
                .arg(Arg::new("manifest").long("manifest").required(true)),
        )
        .subcommand(
            Command::new("inspect").arg(profile_arg()).arg(
                Arg::new("id")
                    .long("id")
                    .allow_hyphen_values(true)
                    .required(true),
            ),
        )
        .subcommand(
            Command::new("status").arg(profile_arg()).arg(
                Arg::new("id")
                    .long("id")
                    .allow_hyphen_values(true)
                    .required(true),
            ),
        )
        .subcommand(
            Command::new("apply")
                .arg(profile_arg())
                .arg(
                    Arg::new("id")
                        .long("id")
                        .allow_hyphen_values(true)
                        .required(true),
                )
                .arg(Arg::new("digest").long("digest").required(true))
                .arg(
                    Arg::new("request-id")
                        .long("request-id")
                        .allow_hyphen_values(true),
                )
                .arg(
                    Arg::new("retry")
                        .long("retry")
                        .action(clap::ArgAction::SetTrue),
                ),
        )
}

fn origin_args() -> Vec<Arg> {
    #[cfg(feature = "local-dev")]
    {
        vec![Arg::new("origin").long("origin").hide(true)]
    }
    #[cfg(not(feature = "local-dev"))]
    {
        vec![]
    }
}
